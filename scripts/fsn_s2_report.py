"""Render S2_summary.md and S5 tier counts from the S2 JSON/CSV outputs (no hand-typed numbers)."""
import csv
import json
from collections import Counter
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "docs" / "paper-upgrade" / "results" / "fsn"
meta = json.load(open(D / "S2_meta.json"))
SYS = ["yolo_raw", "yolo_abstain", "vlm_only", "vlm_only_resolved", "hybrid", "hybrid_resolved"]
f = lambda a: f"{100 * a['acc']:.1f} [{100 * a['ci95'][0]:.1f}, {100 * a['ci95'][1]:.1f}]"
L = ["# S2: labelled fallback ablation (generated by scripts/fsn_s2_report.py)", "",
     f"Images: {meta['n_images']} single-item test images (3/class, seed 0) from {meta['classes_covered']} of {meta['classes_total']} classes. "
     "Accuracy % with 95% bootstrap CI (2000 resamples over images). Match = exact/plural/space-less/synonym; no word-subset matches.",
     "`*_resolved` = VLM name additionally accepted if its knowledge-layer canonical food matches. `hybrid` = YOLO if conf >= threshold, "
     "else Qwen (hinted with YOLO class unless suppressed). `yolo_abstain` = pre-LLM behaviour (below threshold = unknown).", ""]
for t in ("0.3", "0.5", "0.75"):
    s = json.load(open(D / f"S2_summary_t{t}.json"))["accuracy"]
    L += [f"## Threshold {t}", "", "| subset | n | fallback rate | " + " | ".join(SYS) + " |", "|---|---|---|" + "---|" * len(SYS)]
    for k, a in s.items():
        L.append(f"| {k} | {a['n']} | {100 * a['fallback_rate']:.1f}% | " + " | ".join(f(a[x]) for x in SYS) + " |")
    L += ["", "Accuracy on fallback images only (n = images below threshold):", "",
          "| subset | n_fallback | yolo_raw | vlm_only | hybrid | hybrid_resolved |", "|---|---|---|---|---|---|"]
    for k, a in s.items():
        o = a.get("on_fallback_images")
        if o:
            L.append(f"| {k} | {a['n_fallback']} | " + " | ".join(f"{100 * o[x]:.1f}" for x in ("yolo_raw", "vlm_only", "hybrid", "hybrid_resolved")) + " |")
    d = s["all"]["hybrid_resolved_minus_yolo_abstain"]
    L += ["", f"Paired hybrid_resolved - yolo_abstain (all): {100 * d['diff']:.1f} pp [{100 * d['ci95'][0]:.1f}, {100 * d['ci95'][1]:.1f}]", ""]
L += ["## Coverage", "", f"{meta['n_missing']} classes have no single-item test image (not {31}): " + ", ".join(meta["classes_without_single_item_test_image"]), "",
      f"Leak-free subset = test images with no train image at pHash Hamming <= 6 (S3): {meta['n_leak_free']} of {meta['n_images']}.",
      f"MS2 errors: {meta['ms2_errors']}. Latency (ms): {json.dumps(meta['latency_ms'])}", ""]
rows = list(csv.DictReader(open(D / "S5_lookup_tiers.csv")))
uniq = {(r["vlm_name"]): r for r in rows}
L += ["## S5 tier counts", "", f"All VLM calls ({len(rows)}): {dict(Counter(r['tier'] for r in rows))}",
      f"Unique VLM names ({len(uniq)}): {dict(Counter(r['tier'] for r in uniq.values()))}", ""]
(D / "S2_summary.md").write_text("\n".join(L))
print("\n".join(L[-12:]))
