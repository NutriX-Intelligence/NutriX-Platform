"""Render S4_summary.md + S4_macro_source_sensitivity.csv from S4_per_food.csv (no Qwen needed)."""
import csv
import json
import statistics as st
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "docs" / "paper-upgrade" / "results" / "fsn"
recs = list(csv.DictReader(open(D / "S4_per_food.csv")))
num = lambda x: None if x in ("", None) else float(x)
KEYS = ["kcal", "protein", "carbs", "fat"]
SUSPECT_FAT = 55.0     # INDB reference fat > 55 g per 100 g (more than half the dish is fat by weight): treated as suspect


def metrics(est, ref):
    err = [e - r for e, r in zip(est, ref)]
    ape = [abs(e - r) / r * 100 for e, r in zip(est, ref) if r >= 1.0]
    n = len(err)
    if not n:
        return None
    bias, sd = sum(err) / n, (st.stdev(err) if n > 1 else float("nan"))
    return dict(n=n, MAE=round(sum(map(abs, err)) / n, 1), MAPE=round(sum(ape) / len(ape), 1) if ape else None,
                medAPE=round(st.median(ape), 1) if ape else None, bias=round(bias, 1),
                loa=f"[{bias - 1.96 * sd:.1f}, {bias + 1.96 * sd:.1f}]")


def table(rows, label):
    out, csv_rows = [f"### {label} (n = {len(rows)} foods)", "", "| source | nutrient | n | MAE | MAPE % | median APE % | BA bias | 95% LoA |", "|---|---|---|---|---|---|---|---|"], []
    for name, pre, guard in (("i DB", "db", False), ("ii Qwen raw", "qraw", False), ("iii Qwen Atwater", "qatw", False), ("iv Qwen after guardrail", "qatw", True)):
        for k in KEYS:
            pr = [(num(r[f"{pre}_{k}"]), num(r[f"ref_{k}"])) for r in rows if num(r[f"{pre}_{k}"]) is not None and not (guard and r["flagged"] == "True")]
            m = metrics([p[0] for p in pr], [p[1] for p in pr])
            if m:
                out.append(f"| {name} | {k} | {m['n']} | {m['MAE']} | {m['MAPE']} | {m['medAPE']} | {m['bias']} | {m['loa']} |")
                csv_rows.append(dict(subset=label, source=name, nutrient=k, **m))
    return out + [""], csv_rows


suspect = [r for r in recs if float(r["ref_fat"]) > SUSPECT_FAT]
clean = [r for r in recs if float(r["ref_fat"]) <= SUSPECT_FAT]
t1, c1 = table(recs, "All scored foods")
t2, c2 = table(clean, f"Excluding suspect INDB rows (ref fat > {SUSPECT_FAT:g} g/100 g)")
meta = json.load(open(D / "S4_meta.json"))
cw = list(csv.DictReader(open(D / "S4_crosswalk.csv")))
L = ["# S4: macro-source ablation vs INDB (generated by scripts/fsn_s4_report.py)", "",
     f"Reference = INDB per-100 g values. Scored foods: {meta['n_foods_scored']} of {meta['n_foods_total']} in the food set; "
     f"{meta['n_unscored']} unscored (see S4_crosswalk.csv `status`). **No USDA/IFCT file with raw produce is available locally, so all raw/non-Indian foods "
     "(apple, banana, tomato, ...) are unscored; this table is Indian dishes only.** APE is undefined for reference < 1 g/100 g and those foods are dropped from MAPE only.", "",
     "**Suspect reference rows** (INDB fat > 55 g/100 g, physically implausible for these dishes): " + ", ".join(f"{r['food']} ({r['ref_code']}, fat {float(r['ref_fat']):.1f})" for r in suspect) +
     ". Not corrected; both tables are shown.", "",
     "**Circularity check:** the NutriX Indian rows (IND_FOOD_*) are not equal to INDB values (they are hand-entered round numbers), so DB-vs-INDB is an independent comparison.", ""]
L += t1 + t2
conf = meta["guardrail_confusion_on_atwater_kcal"]
L += ["## Guardrail confusion (kcal after Atwater recompute; wrong = kcal APE > 20 % vs INDB)", "", "| | flagged | not flagged |", "|---|---|---|",
      f"| wrong | {conf['wrong_flagged']} | {conf['wrong_not_flagged']} |", f"| correct | {conf['correct_flagged']} | {conf['correct_not_flagged']} |", "",
      f"Raw-kcal version: {json.dumps(meta['guardrail_confusion_on_raw_kcal'])}. Foods flagged in total: {meta['n_flagged']}. "
      "The guardrail checks internal consistency (Atwater, range), not correctness against a reference, and the recompute step makes outputs consistent by construction.", "",
      "## Unscored foods", ""]
for st_, rows in {}.items():
    pass
from collections import Counter
L += [f"{k}: {v}" for k, v in Counter(r["status"].split(":")[0] for r in cw).items()]
(D / "S4_summary.md").write_text("\n".join(L))
with open(D / "S4_macro_source_sensitivity.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(c1[0]))
    w.writeheader()
    w.writerows(c1 + c2)
print("\n".join(L))
