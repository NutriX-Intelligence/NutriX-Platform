"""Generate the FSN v2 summary .md files from the v2 result files (no hand-typed numbers).
  PYTHONPATH=. python scripts/fsn_v2_summaries.py
Writes v2/A_code_fixes_summary.md, v2/S2_summary.md, v2/B2_summary.md.
"""
import csv
import json
from pathlib import Path

V1 = Path(__file__).resolve().parent.parent / "docs" / "paper-upgrade" / "results" / "fsn"
D = V1 / "v2"
SYSTEMS = ["yolo_raw", "yolo_abstain", "vlm_only", "vlm_only_resolved", "hybrid", "hybrid_resolved"]
SUBSETS = ["all", "indian_dishes", "other_foods", "leak_free", "leak_free_indian", "leak_free_other"]


def j(name):
    return json.loads((D / name).read_text())


def cache(path):
    return {json.loads(l)["image"]: json.loads(l) for l in Path(path).read_text().splitlines() if l.strip()}


def s2():
    s = j("S2_summary_test_pc3_s0_t0.5.json")
    meta = j("S2_meta_test_pc3_s0.json")
    v1c, v2c = cache(V1 / "S2_cache_test_pc3_s0.jsonl"), cache(D / "S2_cache_test_pc3_s0.jsonl")
    common = sorted(set(v1c) & set(v2c))
    same = {k: sum(v1c[i][k] == v2c[i][k] for i in common) for k in ("yolo", "yolo_conf", "vlm", "hybrid_vlm")}
    v1s = json.loads((V1 / "S2_summary_t0.5.json").read_text())["accuracy"]
    L = ["# S2 v2: labelled fallback ablation at threshold 0.5 (generated by scripts/fsn_v2_summaries.py)", "",
         f"Test split, {meta['per_class']} single-item images per class, seed {meta['seed']}: n = {meta['n_images']} images, "
         f"{meta['classes_covered']} of {meta['classes_total']} classes; leak-free (no train near-duplicate, S3) n = {meta['n_leak_free']}. "
         f"Fresh YOLO + Qwen run on the fixed code; knowledge-layer resolution uses the current shared.food_lookup "
         f"(partial tier {'on' if meta['food_lookup_partial_enabled'] else 'off'}, empty rows = miss). MS2 errors: {meta['ms2_errors']}.", "",
         f"Reproducibility vs the v1 cache ({len(common)} common images): identical YOLO top-1 {same['yolo']}, identical YOLO conf "
         f"{same['yolo_conf']}, identical unhinted VLM name {same['vlm']}, identical hinted VLM name {same['hybrid_vlm']}.", "",
         "## Accuracy (95 % bootstrap CI)", "",
         "| subset | n | fallback rate | " + " | ".join(SYSTEMS) + " |", "|---|---|---|" + "---|" * len(SYSTEMS)]
    for sub in SUBSETS:
        e = s["accuracy"][sub]
        L.append(f"| {sub} | {e['n']} | {e['fallback_rate']} | " + " | ".join(f"{e[sy]['acc']} [{e[sy]['ci95'][0]}, {e[sy]['ci95'][1]}]" for sy in SYSTEMS) + " |")
    L += ["", "## Paired bootstrap differences (same images)", "",
          "| subset | hybrid_resolved - yolo_raw | 95 % CI | hybrid_resolved - yolo_abstain | 95 % CI |", "|---|---|---|---|---|"]
    for sub in SUBSETS:
        e = s["accuracy"][sub]
        a, b = e["hybrid_resolved_minus_yolo_raw"], e["hybrid_resolved_minus_yolo_abstain"]
        L.append(f"| {sub} | {a['diff']} | {a['ci95']} | {b['diff']} | {b['ci95']} |")
    L += ["", "## On fallback images only (YOLO conf < 0.5 or suppressed class)", "", "| subset | n fallback | yolo_raw | hybrid | hybrid_resolved |", "|---|---|---|---|---|"]
    for sub in SUBSETS:
        e = s["accuracy"][sub]
        fb = e.get("on_fallback_images")
        if fb:
            L.append(f"| {sub} | {e['n_fallback']} | {fb['yolo_raw']} | {fb['hybrid']} | {fb['hybrid_resolved']} |")
    L += ["", "## v1 vs v2 (threshold 0.5, hybrid_resolved accuracy)", "", "| subset | v1 | v2 |", "|---|---|---|"]
    for sub in SUBSETS:
        L.append(f"| {sub} | {v1s[sub]['hybrid_resolved']['acc']} | {s['accuracy'][sub]['hybrid_resolved']['acc']} |")
    L += ["", f"Per-image results: S2_per_image_test_pc3_s0.csv; tiers: S5_lookup_tiers_test_pc3_s0.csv; validation split (used only for B2): "
          "S2_summary_valid_pc3_s0_t0.5.json.", ""]
    (D / "S2_summary.md").write_text("\n".join(L))


def b2():
    rule, res = j("routing_rule.json"), j("B2_routing_test_leakfree.json")
    L = ["# B2: pre-registered Indian-class routing rule (generated by scripts/fsn_v2_summaries.py)", "",
         f"Rule: {rule['rule']}. Main threshold {rule['main_threshold']}.", "",
         f"Tuned on the VALIDATION split only (leak-free vs train, n = {rule['validation_leak_free_n']}); selection: {rule['selection']}. "
         f"routing_rule.json written {rule['written_at']}; the test per-image file did not exist at that time "
         f"(test_per_image_file_existed_at_write = {rule['test_per_image_file_existed_at_write']}).", "",
         "| c | validation accuracy | 95 % CI | images overridden |", "|---|---|---|---|"]
    for c, v in rule["validation_per_c"].items():
        L.append(f"| {c} | {v['acc']} | {v['ci95']} | {v['n_overridden']} |")
    nr = rule["validation_no_rule_hybrid_resolved"]
    L += [f"| no rule | {nr['acc']} | {nr['ci95']} | 0 |", "", f"**Chosen c = {rule['chosen_c']}.**", "",
          f"## Test (leak-free), evaluated once at {res['evaluated_at']}", "",
          "| subset | n | overridden | routed | hybrid_resolved | yolo_raw | routed - hybrid_resolved [CI] | routed - yolo_raw [CI] |", "|---|---|---|---|---|---|---|---|"]
    for sub, e in res["subsets"].items():
        L.append(f"| {sub} | {e['n']} | {e['n_overridden']} | {e['hybrid_resolved_routed']['acc']} {e['hybrid_resolved_routed']['ci95']} | "
                 f"{e['hybrid_resolved']['acc']} {e['hybrid_resolved']['ci95']} | {e['yolo_raw']['acc']} {e['yolo_raw']['ci95']} | "
                 f"{e['routed_minus_hybrid_resolved']['diff']} {e['routed_minus_hybrid_resolved']['ci95']} | {e['routed_minus_yolo_raw']['diff']} {e['routed_minus_yolo_raw']['ci95']} |")
    L += ["", "Reported as evaluated; c was not retuned after seeing the test result.", ""]
    (D / "B2_summary.md").write_text("\n".join(L))


def part_a():
    a1, a2, a3 = j("A1_partial_rule_changes.json"), j("A2_zero_kcal_investigation.json"), j("suspect_db_rows_summary.json")
    changed = [r for r in csv.DictReader(open(D / "A1_partial_rule_changes.csv", newline="")) if r["changed_default"] == "True"]
    sus = list(csv.DictReader(open(D / "suspect_db_rows.csv", newline="")))
    L = ["# Part A: code fixes (generated by scripts/fsn_v2_summaries.py)", "",
         "## A1: partial-match lookup", "",
         "shared/food_lookup.py: the partial tier is OFF unless FOOD_LOOKUP_PARTIAL=true, and even then needs a query of >= 2 words "
         "covering >= 80 % of the candidate name's characters.", "",
         f"On the {a1['n_distinct_name_gt_pairs']} distinct (VLM name, ground truth) pairs of v1 S5 ({a1['n_distinct_names']} distinct names), "
         f"same DB, old rule vs new: {a1['pairs_changed_default']} pairs / {a1['names_changed_default']} names change resolution "
         f"(default, flag off); {a1['pairs_changed_partial_on']} pairs with the flag on. All changed pairs were old-rule partial hits "
         f"({a1['changed_by_old_tier']}); of the {a1['old_partial_pairs']} old partial pairs, {a1['old_partial_pairs_correct']} had resolved to the "
         "ground-truth food. They now go to the miss path (MS2 text lookup).", "",
         "| VLM name | ground truth | old resolution | new |", "|---|---|---|---|"]
    L += [f"| {r['vlm_name']} | {r['gt']} | {r['old_food']} | {r['new_default_tier']} |" for r in changed]
    oreo = a2["foods_with_exact_name"]["oreo"]
    cb = [a for a in a2["audit_logs"] if (a["output"] or {}).get("food_name") == "chocolate bar"]
    L += ["", "## A2: zero-nutrient logging", "",
          f"Chocolate Bar: MS2 audit_logs show both Qwen calls for the capture flagged by the Atwater check "
          + "; ".join(f"#{a['id']} {a['operation']} flagged={a['flagged']} ({(a['output'] or {}).get('flag_reason')})" for a in cb[:2])
          + f". 'chocolate bar' has no DB row (current tier: {a2['resolution']['chocolate bar']['current']['tier']}), so no source had macros and "
          "ms1_cv/main.py logged zeros as a normal esp32_qwen_vlm meal.", "",
          f"Oreo: {len(oreo)} foods rows are named 'oreo' case-insensitively: "
          + "; ".join(f"{o['food_code']} '{o['name']}' {o['kcal']} kcal" for o in oreo)
          + ". At the demo commit the exact tier took .first() with no ordering, so the all-zero row could win and be logged as a 'db' hit "
          "with 0 kcal (the demo meal_logs rows were removed by the session reset, so this is inferred from the code and the DB rows; "
          "later Oreo captures are logged at 483 kcal/100 g).", "",
          f"DB: {a2['foods_with_null_or_zero_energy']} of {a2['foods_total']} foods rows have null/0 energy; "
          f"{a2['foods_with_null_or_zero_energy_but_macros']} of them have non-zero macro grams (the old rule treated those as usable hits).", "",
          "Fix: a null/0-energy DB row is a miss (unless the food is ~0 kcal: water, black coffee, diet soda, ...), so it goes to the MS2 text "
          "lookup; a 0 kcal MS2 answer is not trusted either; if nothing has macros the meal is logged with meal_logs.source = "
          "'no_nutrition_data' (existing free-text column, no migration, no API schema change; MS3 passes source through as Optional[str]). "
          "The Flutter source is not on this machine, so the app could not be read; docs/APP_HANDOFF.md documents the new value.", "",
          "## A3: suspect DB rows", "",
          f"{a3['n_db_rows_compared_with_indb']} DB rows matched an INDB row (rules in scripts/fsn_a3_suspect_rows.py); "
          f"{a3['n_suspect_vs_indb']} differ by > 50 % in kcal/100 g. Full list: suspect_db_rows.csv (Mixed Nuts first); "
          "all compared rows: A3_db_vs_indb_all.csv. Nothing was changed.", ""]
    mn = a3["mixed_nuts"]
    L += [f"Mixed Nuts (LLM_mixed_nuts, brand LLM Inferred): {mn['db_kcal']} kcal, {mn['db_protein']} g protein, {mn['db_carbs']} g carbs, "
          f"{mn['db_fat']} g fat per 100 g, persisted from an unflagged MS2 Qwen text lookup; reference {mn['ref_code']} '{mn['ref_name']}' "
          f"{mn['ref_kcal']} kcal ({mn['kcal_rel_diff']:+.1%}).", "",
          "| food_code | name | DB kcal | reference | ref kcal | rel. diff |", "|---|---|---|---|---|---|"]
    L += [f"| {r['food_code']} | {r['name']} | {r['db_kcal']} | {r['ref_code']} {r['ref_name'][:40]} | {float(r['ref_kcal']):.1f} | {r['kcal_rel_diff']} |" for r in sus]
    L += ["", "## A4: threshold", "", "`.env` YOLO_CONF_THRESHOLD changed from 0.7 to 0.5 (the value evaluated in S2).", ""]
    (D / "A_code_fixes_summary.md").write_text("\n".join(L))


if __name__ == "__main__":
    part_a()
    s2()
    b2()
    print("ok")
